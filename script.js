/* =========================================
COMENTARIOS
========================================= */

const publishBtn =
document.querySelector(".publish-btn");

const commentsBox =
document.querySelector(".comments-box");

const textarea =
document.querySelector("textarea");

if(publishBtn){

publishBtn.addEventListener("click", ()=>{

const text = textarea.value.trim();

if(text === "") return;

const comment = document.createElement("div");

comment.classList.add("new-comment");

comment.style.marginTop = "15px";
comment.style.padding = "14px";
comment.style.borderRadius = "12px";
comment.style.background = "#f5f5f5";

comment.innerHTML = `
<strong>Usuario:</strong>
<p>${text}</p>
`;

commentsBox.appendChild(comment);

textarea.value = "";

});

}

/* =========================================
ESTRELLAS
========================================= */

const stars =
document.querySelectorAll(".stars i");

let currentRating = 0;

stars.forEach((star,index)=>{

star.addEventListener("click", ()=>{

currentRating = index + 1;

stars.forEach((s,i)=>{

if(i < currentRating){

s.style.color = "#ffbf00";

}else{

s.style.color = "#ccc";

}

});

});

});

